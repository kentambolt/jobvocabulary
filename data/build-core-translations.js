const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname,'..');
const source = path.resolve(process.argv[2] || path.join(root,'.private/jobvocabulary-private/content/translations/core-pl-ro.json'));
const data = JSON.parse(fs.readFileSync(source,'utf8'));
const { WORD_ROWS } = require('../words');
const rows = {};
for(const [id] of WORD_ROWS) {
  const row = data.rows[id];
  if(!row || ['pl','ro'].some(l=>typeof row[l]!=='string'||row[l].length>300)) throw new Error('Missing or invalid core translation: '+id);
  rows[id] = { pl:row.pl.trim(),ro:row.ro.trim() };
}
if(Object.keys(data.rows).length!==WORD_ROWS.length) throw new Error('Unknown or missing core IDs');
const draft = /functional QA only/i.test(data.status || '');
fs.writeFileSync(path.join(root,'core-translations.js'),(draft ? '// FUNCTIONAL QA DRAFT: replace with reviewed delivery before publishing.\n' : '// Generated by data/build-core-translations.js; source reviews remain private.\n')+'var CORE_TRANSLATIONS = '+JSON.stringify(rows)+';\nif(typeof module!=="undefined") module.exports=CORE_TRANSLATIONS;\n');
console.log(Object.keys(rows).length+' core concepts translated.');
