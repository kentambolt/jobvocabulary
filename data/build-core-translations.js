const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname,'..');
const { WORD_ROWS } = require('../words');
const sources = process.argv.slice(2);
if (!sources.length) for (const pair of ['pl-ro','lt-bg']) sources.push(path.join(root,'.private/jobvocabulary-private/content/translations/core-'+pair+'.json'));
const rows = Object.fromEntries(WORD_ROWS.map(([id])=>[id,{}]));
const added = new Set();
for (const source of sources) {
  const data = JSON.parse(fs.readFileSync(path.resolve(source),'utf8'));
  if (/functional QA only/i.test(data.status || '')) throw new Error('Draft delivery cannot be published');
  if (!data.languages?.length || data.languages.some(lang=>!['pl','ro','lt','bg'].includes(lang) || added.has(lang))) throw new Error('Unexpected or repeated language');
  for (const lang of data.languages) added.add(lang);
  for (const [id] of WORD_ROWS) {
    const row = data.rows[id];
    if (!row || data.languages.some(lang=>typeof row[lang]!=='string'||row[lang].length>300)) throw new Error('Missing or invalid core translation: '+id);
    for (const lang of data.languages) rows[id][lang] = row[lang].trim();
  }
  if(Object.keys(data.rows).length!==WORD_ROWS.length) throw new Error('Unknown or missing core IDs');
}
fs.writeFileSync(path.join(root,'core-translations.js'),'// Generated by data/build-core-translations.js; source reviews remain private.\nvar CORE_TRANSLATIONS = '+JSON.stringify(rows)+';\nif(typeof module!=="undefined") module.exports=CORE_TRANSLATIONS;\n');
console.log(Object.keys(rows).length+' core concepts translated.');
