const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const locales = Object.fromEntries(['pl','ro','lt','bg'].map(lang => [lang, JSON.parse(fs.readFileSync(path.join(root,'locales',lang+'.json'),'utf8'))]));
fs.writeFileSync(path.join(root,'locales.js'), '// Generated by data/build-locales.js\nvar EXTRA_LOCALES = '+JSON.stringify(locales)+';\nif (typeof module !== "undefined") module.exports = EXTRA_LOCALES;\n');
